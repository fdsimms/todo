#!/usr/bin/env node
// Rewrites docs/repo-stats.md, which holds the repo's own measurements — how
// many test suites there are, and which files are big enough that reading one
// end to end costs more than the task will.
//
// It lived inside CLAUDE.md as a marked block until the numbers moved on every
// branch at once and made CLAUDE.md conflict for every open PR. It is its own
// file now so it can carry `merge=union` in .gitattributes without that
// applying to CLAUDE.md's prose; see the .gitattributes comment.
//
// Those numbers govern how an agent spends its context, and they had drifted
// badly: the file claimed seven files over 1,000 lines when there were 34, and
// listed useTaskStore.ts at 1.5k when it was 4,660. Prose nobody can verify
// goes stale silently, so this block is generated and CI checks it.
//
// Only statically derivable facts go in here. Wall-clock timings depend on the
// machine and the test count depends on `describe.each` expansion, so both stay
// as hand-written prose that says "about" and means it.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const guideFile = path.join(root, 'CLAUDE.md');
const statsFile = path.join(root, 'docs', 'repo-stats.md');
const BIG_FILE_LINES = 1000;

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(abs, out);
    else if (/\.tsx?$/.test(entry.name)) out.push(abs);
  }
  return out;
}

// mcp/src alongside src because the MCP server's tests run in this repo's jest
// like everything else (see docs/arch/mcp-server.md) — a suite count that only
// walked src/ would understate what `npm test` costs, which is the one job this
// number has.
const SOURCE_DIRS = ['src', 'mcp/src'];

const files = SOURCE_DIRS.flatMap(dir => {
  const abs = path.join(root, dir);
  return fs.existsSync(abs) ? walk(abs) : [];
}).map(abs => {
  const text = fs.readFileSync(abs, 'utf8');
  return {
    rel: path.relative(root, abs).split(path.sep).join('/'),
    lines: text.split('\n').length,
    banners: /^\s*\/\/ ====/m.test(text),
  };
});

const suites = files.filter(f => /\.test\.tsx?$/.test(f.rel)).length;
const big = files.filter(f => f.lines >= BIG_FILE_LINES).sort((a, b) => b.lines - a.lines);
const bigSource = big.filter(f => !/\.test\.tsx?$/.test(f.rel));

// A component or screen this big is almost always one component holding most
// of the file, with nothing at the top level to grep for, so CLAUDE.md asks it
// to carry a header map and `// ====` banners. Listing the ones that don't is
// what keeps that rule from depending on a hand-kept list of file names.
const unmapped = bigSource
  .filter(f => /^src\/(components|screens)\/.*\.tsx$/.test(f.rel) && !f.banners)
  .map(f => f.rel.replace(/^src\//, ''))
  .sort();

const k = n => `${(n / 1000).toFixed(1)}k`;
const named = bigSource.slice(0, 10).map(f => `\`${f.rel.replace(/^src\//, '')}\` (${k(f.lines)})`);

// Wrap a file list so the block stays readable as source, like the prose
// around it.
function wrap(entries) {
  const out = [];
  let line = '';
  for (const entry of entries) {
    const piece = line ? `${line}, ${entry}` : entry;
    if (piece.length > 92 && line) {
      out.push(`${line},`);
      line = entry;
    } else {
      line = piece;
    }
  }
  if (line) out.push(`${line}.`);
  return out;
}
const wrapped = wrap(named);

const block = [
  '<!-- AUTO-GENERATED by scripts/check-doc-stats.js \u2014 do not edit by hand. -->',
  '',
  '# Repo stats',
  '',
  "The repo's own measurements, regenerated by `node scripts/check-doc-stats.js`;",
  'CI fails if it is out of date. Run it after adding or growing a file.',
  '',
  `**Read narrowly.** ${big.length} files are over ${BIG_FILE_LINES.toLocaleString()} lines, ${bigSource.length} of`,
  'them source rather than tests. The ten biggest source files:',
  '',
  ...wrapped,
  '',
  'Grep for the symbol and read the surrounding range; reading any of them end to end costs more',
  'context than the rest of the task will. `docs/module-map.md` says which file owns what.',
  '',
  ...(unmapped.length
    ? [
        `**Components and screens over ${BIG_FILE_LINES.toLocaleString()} lines with no \`// ====\` banners.** Any of these that is`,
        'one component holding most of the file is owed a header map and banners (CLAUDE.md,',
        '"single-component files"); one with real top-level symbols to grep for is not:',
        '',
        ...wrap(unmapped.map(f => `\`${f}\``)),
        '',
      ]
    : []),
  `The suite is **${suites} test files**, and \`npm test\` runs all of them in about a minute.`,
  '`npx tsc --noEmit` is a few seconds once `.tsbuildinfo` exists.',
  '',
].join('\n');

const current = fs.existsSync(statsFile) ? fs.readFileSync(statsFile, 'utf8') : null;

if (process.argv.includes('--check')) {
  if (current !== block) {
    console.error(
      'check-doc-stats: docs/repo-stats.md is out of date.\n' +
        'Run `node scripts/check-doc-stats.js` and commit the result.'
    );
    process.exit(1);
  }
  console.log('check-doc-stats: docs/repo-stats.md is up to date.');
} else {
  fs.writeFileSync(statsFile, block);
  console.log(
    `check-doc-stats: ${suites} test files, ${big.length} files over ${BIG_FILE_LINES} lines.`
  );
}

// Every repo-relative path named in CLAUDE.md, .claude/rules/ or docs/ must resolve. The
// routing table is only worth reading if its rows still point at something, and
// a renamed file (patches/react-native+0.81.4.patch, once) breaks it silently.
const PATH_RE = /`((?:src|docs|scripts|modules|targets|plugins|patches)\/[A-Za-z0-9_./+-]+)`/g;
const PLACEHOLDERS = new Set(['src/utils/foo.ts', 'src/__tests__/foo.test.ts']);

function docFiles(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) docFiles(abs, out);
    else if (entry.name.endsWith('.md')) out.push(abs);
  }
  return out;
}

// The path-scoped rules CLAUDE.md hands most of its sections to. Each loads only when a file its
// `paths:` frontmatter matches is read or edited, which is the whole point of them.
const rulesDir = path.join(root, '.claude', 'rules');
const ruleFiles = fs.existsSync(rulesDir) ? docFiles(rulesDir) : [];

const broken = [];
for (const file of [guideFile, ...ruleFiles, ...docFiles(path.join(root, 'docs'))]) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(PATH_RE)) {
    const ref = m[1].replace(/[.,]$/, '');
    if (PLACEHOLDERS.has(ref)) continue;
    if (!fs.existsSync(path.join(root, ref))) {
      broken.push(`${path.relative(root, file)} -> ${ref}`);
    }
  }
}

if (broken.length) {
  console.error('check-doc-stats: documentation points at paths that do not exist:');
  for (const b of [...new Set(broken)]) console.error(`  ${b}`);
  process.exit(1);
}

// CLAUDE.md is loaded into every session and every general-purpose subagent, so each line in it
// costs every task, whatever the task touches. It reached 208,000 characters (~50k tokens) before
// it was split into the rules files; this keeps it from growing back. A rules file has its own
// ceiling for a different reason: an on-demand memory file past 40,000 characters is cut off, and
// a 200K-context session sees only its start.
const GUIDE_MAX_CHARS = 50000;
const RULE_MAX_CHARS = 38000;
const oversize = [];
const guideChars = fs.readFileSync(guideFile, 'utf8').length;
if (guideChars > GUIDE_MAX_CHARS) {
  oversize.push(
    `CLAUDE.md is ${guideChars.toLocaleString()} characters (limit ${GUIDE_MAX_CHARS.toLocaleString()}). Move a ` +
      'section about one layer or folder into a .claude/rules/ file whose `paths:` cover that code, ' +
      'or a feature rule into its docs/arch/ file, and leave a line in "Rules that load by path".'
  );
}
for (const file of ruleFiles) {
  const chars = fs.readFileSync(file, 'utf8').length;
  if (chars > RULE_MAX_CHARS) {
    oversize.push(
      `${path.relative(root, file)} is ${chars.toLocaleString()} characters (limit ${RULE_MAX_CHARS.toLocaleString()}). ` +
        'Split it into two rules files with the same `paths:`.'
    );
  }
}
if (oversize.length) {
  console.error('check-doc-stats: an instruction file is over its size limit:');
  for (const o of oversize) console.error(`  ${o}`);
  process.exit(1);
}

// Every glob in a rules file's `paths:` must still match something. A rule whose files were all
// renamed away never loads again, and nothing about that is visible.
function globToRegExp(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') {
      re += glob[i + 2] === '/' ? '(?:.*/)?' : '.*';
      i += glob[i + 2] === '/' ? 2 : 1;
    } else if (c === '*') re += '[^/]*';
    else re += c.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}
const repoFiles = require('child_process')
  .execSync('git ls-files --cached --others --exclude-standard', { cwd: root, encoding: 'utf8' })
  .split('\n')
  .filter(Boolean);
const deadGlobs = [];
for (const file of ruleFiles) {
  const front = fs.readFileSync(file, 'utf8').match(/^---\n([\s\S]*?)\n---\n/);
  const globs = front ? [...front[1].matchAll(/^\s+-\s+"([^"]+)"/gm)].map(m => m[1]) : [];
  if (!globs.length) deadGlobs.push(`${path.relative(root, file)} has no \`paths:\`, so it loads into every session`);
  for (const glob of globs) {
    const re = globToRegExp(glob);
    if (!repoFiles.some(f => re.test(f))) deadGlobs.push(`${path.relative(root, file)} -> ${glob}`);
  }
}
if (deadGlobs.length) {
  console.error('check-doc-stats: a rules file names paths that match nothing:');
  for (const d of deadGlobs) console.error(`  ${d}`);
  process.exit(1);
}

// A comment that cites a write-up by section ("docs/arch/workouts.md, \"Gyms\"") must name a
// heading or a bold rule lead-in that is really there. Six files once cited a "Gyms" section that
// had never been written, and a renamed heading leaves its citations pointing at nothing, with no
// way to tell from the comment. A citation matches when it is the start of one (a heading is cited
// by its opening words, often up to its dash). A bold span that is only a code name (`**`gyms`**`,
// a table in a schema list) is not a lead-in, or "Gyms" would have passed against the table name.
const normalize = s => s.replace(/[`*_]/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
const citable = new Map();
for (const file of docFiles(path.join(root, 'docs'))) {
  const text = fs.readFileSync(file, 'utf8');
  const targets = [
    ...[...text.matchAll(/^#{1,6}\s+(.+)$/gm)].map(m => m[1]),
    ...[...text.matchAll(/\*\*([^*]+?)\*\*/g)].map(m => m[1]).filter(b => !/^`[^`]+`$/.test(b.trim())),
  ].map(normalize);
  citable.set(path.basename(file), targets);
}
const CITATION = /([a-z0-9-]+\.md)[`'"]?[,:]?\s*\(?\s*["“]([^"”]{3,100})["”]/g;
const staleCitations = [];
for (const rel of repoFiles) {
  if (!/\.(ts|tsx|js|swift|md)$/.test(rel) || /(^|\/)node_modules\//.test(rel)) continue;
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) continue;
  // Join wrapped comment lines, so a citation broken across two lines still reads as one.
  const text = fs.readFileSync(abs, 'utf8').replace(/\n\s*(?:\*|\/\/+|--|#)?\s*/g, ' ');
  for (const m of text.matchAll(CITATION)) {
    const targets = citable.get(m[1]);
    if (!targets) continue;
    const cited = normalize(m[2]);
    if (!targets.some(t => t.startsWith(cited))) {
      staleCitations.push(`${rel} -> ${m[1]}, "${m[2].replace(/\s+/g, ' ').trim()}"`);
    }
  }
}
if (staleCitations.length) {
  console.error('check-doc-stats: a citation names a section that is not in the doc (fix the citation, or the heading it meant):');
  for (const c of [...new Set(staleCitations)]) console.error(`  ${c}`);
  process.exit(1);
}
