#!/usr/bin/env node
// Writes docs/module-map.md — one line per logic-layer module, naming its
// exported symbols. It exists because CLAUDE.md's routing table covers the
// features someone wrote prose about, which is about half of src/utils by
// volume; the other half (sync, backup, calendar, rhythms, blocking) had no
// entry point at all short of grepping blind.
//
// Deliberately only utils/store/hooks/db/services. Components and screens are
// named after what they render, so a line saying `TaskEditor.tsx: TaskEditor`
// costs context and tells nobody anything.
//
// Committed rather than gitignored — an agent has to be able to read it
// without running a build first. `--check` is what keeps it honest, and CI
// runs it on every PR.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'docs', 'module-map.md');
const DIRS = ['src/utils', 'src/store', 'src/hooks', 'src/db', 'src/services'];
const MAX_SYMBOLS = 10;

// Top-level exported declarations only. A re-export or an `export {}` list
// isn't where a symbol is defined, so it isn't what a reader wants to open.
const EXPORT_RE = /^export\s+(?:default\s+)?(?:async\s+)?(?:const|let|function|type|interface|class|enum)\s+([A-Za-z0-9_$]+)/gm;

function symbolsOf(file) {
  const src = fs.readFileSync(file, 'utf8');
  const names = [];
  for (const m of src.matchAll(EXPORT_RE)) names.push(m[1]);
  return names;
}

function render() {
  const lines = [
    '<!-- AUTO-GENERATED by scripts/build-module-map.js — do not edit by hand. -->',
    '',
    '# Module map',
    '',
    'Every module in the logic layer, with the symbols it exports. Regenerated by',
    '`node scripts/build-module-map.js`; CI fails if it is out of date.',
    '',
    'This is an index, not documentation. It answers "which file owns this" so you',
    'can grep one file instead of the tree. Where a module is written up properly,',
    "CLAUDE.md's routing table says so and that write-up is the authority.",
    '',
    'Components and screens are omitted on purpose: they are named after what they',
    'render, so listing them adds lines without adding answers.',
    '',
  ];

  for (const dir of DIRS) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    const files = fs
      .readdirSync(abs)
      .filter(f => /\.tsx?$/.test(f))
      .sort();
    if (!files.length) continue;

    lines.push(`## \`${dir}\``, '');
    for (const f of files) {
      const rel = `${dir}/${f}`;
      const names = symbolsOf(path.join(abs, f));
      const shown = names.slice(0, MAX_SYMBOLS).join(', ');
      const more = names.length > MAX_SYMBOLS ? `, +${names.length - MAX_SYMBOLS} more` : '';
      lines.push(`- \`${rel}\` — ${shown || '(no top-level exports)'}${more}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

const next = render();
const check = process.argv.includes('--check');

if (check) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== next) {
    console.error(
      'build-module-map: docs/module-map.md is out of date.\n' +
        'Run `node scripts/build-module-map.js` and commit the result.'
    );
    process.exit(1);
  }
  console.log('build-module-map: docs/module-map.md is up to date.');
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, next);
  console.log(`build-module-map: wrote ${path.relative(process.cwd(), outFile)}`);
}
