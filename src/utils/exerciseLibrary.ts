import type { ExerciseEquipment, ExerciseKind, MuscleGroup } from '../types';

/**
 * The built-in exercises: what the Workouts library lists before the person
 * adds anything of their own. See docs/arch/workouts.md.
 *
 * In code rather than in rows, so it updates with the app and costs no sync:
 * hundreds of rows on every device, and a migration for every correction, was
 * the alternative and was rejected. A custom exercise and the person's changes
 * to one of these are rows (`Exercise`), merged over this list by
 * `src/utils/exerciseCatalog.ts`.
 *
 * **An id is forever.** Every logged set, routine item and override row names
 * one of these by id, so an id is never renamed or reused, even when the name
 * beside it is corrected; a retired exercise stays in the list. The id is
 * written out rather than derived from the name for exactly that reason.
 *
 * The muscles are where the work is, not every muscle that moves: primary is
 * what the movement trains, secondary is what helps. Accuracy matters more
 * than count, since a filter by muscle that lists the wrong exercises is worse
 * than a shorter list. The cue is one plain sentence on how to do it, written
 * here. Photos are `exerciseImages.ts`'s, fetched rather than bundled; there is no video.
 */
export interface LibraryExercise {
  /** `lib:` and a slug. Stable for good, see above. */
  id: string;
  name: string;
  kind: ExerciseKind;
  equipment: ExerciseEquipment;
  primaryMuscles: MuscleGroup[];
  secondaryMuscles: MuscleGroup[];
  /** One short sentence on how it's done. */
  cue: string;
}

