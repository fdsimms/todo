/** Every built-in exercise, in the order the library lists them by area. */
export const EXERCISE_LIBRARY: readonly LibraryExercise[] = ROWS.map(
  ([slug, name, kind, equipment, primaryMuscles, secondaryMuscles, cue]) => ({
    id: `${LIBRARY_ID_PREFIX}${slug}`,
    name,
    kind,
    equipment,
    primaryMuscles,
    secondaryMuscles,
    cue,
  })
);

const BY_ID: ReadonlyMap<string, LibraryExercise> = new Map(EXERCISE_LIBRARY.map(e => [e.id, e]));

/** The built-in exercise with this id, or undefined (a custom id, or one this build doesn't have). */
export function libraryExercise(id: string): LibraryExercise | undefined {
  return BY_ID.get(id);
}

/** Whether an id names a built-in exercise, by its prefix, whether or not this build has it. */
export function isLibraryId(id: string): boolean {
  return id.startsWith(LIBRARY_ID_PREFIX);
}
